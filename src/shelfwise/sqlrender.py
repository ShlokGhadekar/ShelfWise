"""Tiny, safe SQL templating for the files in sql/.

Why not just f-strings? Two reasons:
1. The same feature SQL must run on Postgres (pipeline) and DuckDB (unit tests),
   and server-side bind parameters work differently in each. Rendering a handful of
   *numbers and dates* client-side keeps one portable SQL text.
2. Safety: we only substitute ints, floats, dates and explicitly trusted fragments.
   A plain string raises an error, so user input can never be pasted into SQL
   (the classic SQL-injection beginner mistake).

Placeholders look like {name}. Other braces in the SQL are left untouched.
"""

from __future__ import annotations

import datetime as dt
import numbers
import re
from pathlib import Path

SQL_DIR = Path(__file__).resolve().parents[2] / "sql"
_PLACEHOLDER = re.compile(r"\{([a-z_][a-z0-9_]*)\}")


class Trusted(str):
    """Marks a SQL fragment generated by our own code (e.g. a validated subset filter)."""


def _literal(name: str, value: object) -> str:
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, numbers.Integral):  # also catches numpy ints
        return str(int(value))
    if isinstance(value, numbers.Real):
        return repr(float(value))
    if isinstance(value, dt.date):
        return value.isoformat()
    if isinstance(value, Trusted):
        return str(value)
    raise TypeError(f"SQL param {name!r} has unsupported type {type(value).__name__}; wrap trusted fragments in Trusted()")


def render(sql: str, **params: object) -> str:
    def sub(m: re.Match) -> str:
        key = m.group(1)
        if key not in params:
            raise KeyError(f"Missing SQL parameter {{{key}}}")
        return _literal(key, params[key])

    return _PLACEHOLDER.sub(sub, sql)


def load(relative_path: str, **params: object) -> str:
    return render((SQL_DIR / relative_path).read_text(), **params)
